# --- extraction ---------------------------------------------------------

def test_extract_archive_extracts_content_and_nesting(tmp_path):
    # Runs on every OS: what lands on disk is the archive's bytes, nested
    # as stored — the mode questions live in the test below.
    archive = write_zip(tmp_path / "a.zip", [
        ("top/", b"", 0),
        ("top/bin", b"binary", 0o755),
        ("top/dir/nested.txt", b"text", 0o644),
    ])
    destination = tmp_path / "out"
    install_chromium.extract_archive(archive, destination)
    assert (destination / "top" / "bin").read_bytes() == b"binary"
    assert (destination / "top" / "dir" / "nested.txt") \
        .read_bytes() == b"text"


@pytest.mark.skipif(os.name == "nt",
                    reason="mode semantics are POSIX-only and the browser "
                           "consumers are ubuntu-latest")
def test_extract_archive_modes_mask_world_bits(tmp_path):
    # Extraction fidelity, modulo the owner-only mask: the extractor honors
    # the archive's unix modes with everything past the owner bits stripped
    # (CodeQL py/overly-permissive-file flags group bits too), so a 0755
    # entry lands 0700 and a 0644 entry lands 0600.
    archive = write_zip(tmp_path / "a.zip", [
        ("top/", b"", 0),
        ("top/bin", b"binary", 0o755),
        ("top/dir/nested.txt", b"text", 0o644),
    ])
    destination = tmp_path / "out"
    install_chromium.extract_archive(archive, destination)
    assert (destination / "top" / "bin").stat().st_mode & 0o777 == 0o700
    assert (destination / "top" / "dir" / "nested.txt") \
        .stat().st_mode & 0o777 == 0o600


def test_extract_archive_refuses_symlink_entries(tmp_path):
    archive = write_zip(tmp_path / "link.zip", [
        ("top/bin", b"binary", 0o755),
    ])
    forged = zipfile.ZipInfo("top/evil")
    forged.external_attr = 0o120777 << 16
    with zipfile.ZipFile(archive, "a") as appended:
        appended.writestr(forged, b"../../target")
    with pytest.raises(install_chromium.InstallError, match="symlink"):
        install_chromium.extract_archive(archive, tmp_path / "out")


def test_extract_archive_refuses_zip_slip(tmp_path):
    for evil in ("../evil", "/abs/evil"):
        archive = write_zip(tmp_path / "slip.zip", [
            ("top/bin", b"binary", 0o755),
        ])
        with zipfile.ZipFile(archive, "a") as appended:
            appended.writestr(zipfile.ZipInfo(evil), b"escaped")
        with pytest.raises(install_chromium.InstallError,
                           match="escapes"):
            install_chromium.extract_archive(archive, tmp_path / "out")


def test_extract_archive_bad_zip_cleans_up(tmp_path):
    archive = tmp_path / "garbage.zip"
    archive.write_bytes(b"not a zip at all")
    destination = tmp_path / "out"
    destination.mkdir()
    with pytest.raises(install_chromium.InstallError, match="extracting"):
        install_chromium.extract_archive(archive, destination)
    assert not destination.exists()


# --- seeding ------------------------------------------------------------

def test_seed_product_downloads_verifies_and_marks(browsers_root, digests,
                                                   stub_downloads):
    chromium = products(digests)[0]
    outcome = install_chromium.seed_product(browsers_root, chromium)
    assert outcome == "downloaded"
    product_dir = install_chromium.install_dir(browsers_root, chromium)
    assert (product_dir / "chrome-linux64" / "chrome").read_bytes() \
        .startswith(b"#!/bin/sh")
    assert (product_dir / "INSTALLATION_COMPLETE").exists()
    record = json.loads(
        (product_dir / "DIGEST_VERIFIED").read_text(encoding="utf-8"))
    assert record["product"] == "chromium"
    assert record["revision"] == REVISION
    assert record["sha256"] == digests[("chromium", REVISION)]
    executable = product_dir / "chrome-linux64" / "chrome"
    # Mode semantics are POSIX-only and the browser consumers are
    # ubuntu-latest: Windows reports a fixed st_mode, so the assertion is
    # meaningless there — every non-mode assertion above ran on all OSes.
    if os.name != "nt":
        assert executable.stat().st_mode & 0o111
    assert stub_downloads == [[
        "https://cdn.playwright.dev/builds/cft/153.0.8010.12/linux64/"
        "chrome-linux64.zip"]]


def test_seed_product_is_idempotent_when_verified(browsers_root, digests,
                                                  stub_downloads):
    chromium = products(digests)[0]
    install_chromium.seed_product(browsers_root, chromium)
    outcome = install_chromium.seed_product(browsers_root, chromium)
    assert outcome == "already-verified"
    assert len(stub_downloads) == 1  # the second call downloaded nothing


def test_seed_product_replaces_an_unverified_install(browsers_root,
                                                     digests,
                                                     stub_downloads):
    chromium = products(digests)[0]
    product_dir = install_chromium.install_dir(browsers_root, chromium)
    product_dir.mkdir(parents=True)
    (product_dir / "INSTALLATION_COMPLETE").write_bytes(b"")
    (product_dir / "chrome-linux64").mkdir()
    (product_dir / "chrome-linux64" / "chrome").write_bytes(b"TAMPERED")
    outcome = install_chromium.seed_product(browsers_root, chromium)
    assert outcome == "replaced-unverified"
    assert (product_dir / "chrome-linux64" / "chrome").read_bytes() \
        .startswith(b"#!/bin/sh")
    assert (product_dir / "DIGEST_VERIFIED").exists()


def test_seed_product_replaces_stale_provenance(browsers_root, digests,
                                                stub_downloads):
    chromium = products(digests)[0]
    product_dir = install_chromium.install_dir(browsers_root, chromium)
    product_dir.mkdir(parents=True)
    (product_dir / "DIGEST_VERIFIED").write_text(
        json.dumps({"sha256": "0" * 64}), encoding="utf-8")
    outcome = install_chromium.seed_product(browsers_root, chromium)
    assert outcome == "replaced-unverified"


def test_seed_product_fails_loudly_on_digest_mismatch(browsers_root,
                                                      monkeypatch,
                                                      digests):
    chromium = products(digests)[0]
    monkeypatch.setattr(
        install_chromium, "download_archive",
        lambda urls, destination, label, timeout=0: ("b" * 64, 5))
    with pytest.raises(install_chromium.InstallError) as raised:
        install_chromium.seed_product(browsers_root, chromium)
    message = str(raised.value)
    assert digests[("chromium", REVISION)] in message  # expected
    assert "b" * 64 in message                         # actual
    assert "refusing to seed or execute" in message
    product_dir = install_chromium.install_dir(browsers_root, chromium)
    assert not product_dir.exists()


def test_seed_product_fails_when_executable_missing(browsers_root,
                                                    monkeypatch, digests,
                                                    tmp_path):
    noexe = write_zip(tmp_path / "shell-noexe.zip", [
        ("chrome-headless-shell-linux64/ABOUT", b"nothing executable\n",
         0o644),
    ])
    digests = dict(digests)
    digests[("chromium-headless-shell", REVISION)] = _sha256(noexe)
    shell = products(digests)[1]

    def fake_download(urls, destination, label, timeout=0):
        shutil.copyfile(noexe, destination)
        return _sha256(noexe), noexe.stat().st_size

    monkeypatch.setattr(install_chromium, "download_archive", fake_download)
    with pytest.raises(install_chromium.InstallError,
                       match="missing or not executable"):
        install_chromium.seed_product(browsers_root, shell)
    # nothing half-seeded is left for playwright to consider installed
    assert not install_chromium.install_dir(browsers_root, shell).exists()


