def test_build_products_resolves_revision_digest_and_urls(digests):
    seeded = products(digests)
    by_name = {product.spec.name: product for product in seeded}
    assert [product.spec.name for product in seeded] == [
        "chromium", "chromium-headless-shell", "ffmpeg"]
    assert by_name["chromium"].revision == REVISION
    assert by_name["chromium"].browser_version == BROWSER_VERSION
    assert by_name["chromium"].digest == digests[("chromium", REVISION)]
    assert by_name["ffmpeg"].browser_version is None
    assert install_chromium.archive_urls(by_name["chromium"]) == [
        "https://cdn.playwright.dev/builds/cft/153.0.8010.12/linux64/"
        "chrome-linux64.zip"]
    assert install_chromium.archive_urls(by_name["chromium-headless-shell"]) \
        == ["https://cdn.playwright.dev/builds/cft/153.0.8010.12/linux64/"
            "chrome-headless-shell-linux64.zip"]
    assert install_chromium.archive_urls(by_name["ffmpeg"]) == [
        "https://cdn.playwright.dev/builds/ffmpeg/1011/ffmpeg-linux.zip",
        "https://playwright.download.prss.microsoft.com/builds/ffmpeg/1011/"
        "ffmpeg-linux.zip",
    ]


def test_build_products_digest_miss_is_trust_on_first_use(digests):
    reduced = dict(digests)
    del reduced[("chromium", REVISION)]
    with pytest.raises(install_chromium.InstallError) as raised:
        install_chromium.build_products(registry(), reduced)
    message = str(raised.value)
    # the recipe: where the row goes, the revision to key it by, the URL to
    # hash, and the refusal to download anything until it lands
    assert f'("chromium", "{REVISION}")' in message
    assert "builds/cft/153.0.8010.12/linux64/chrome-linux64.zip" in message
    assert "sha256sum" in message
    assert "DIGESTS" in message
    assert "Nothing is downloaded" in message


