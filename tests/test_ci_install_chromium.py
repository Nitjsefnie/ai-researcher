def test_seed_product_downloads_verifies_and_marks(browsers_root, digests,
                                                   stub_downloads):
    chromium = products(digests)[0]
    outcome = install_chromium.seed_product(browsers_root, chromium)
    assert outcome == "downloaded"
    product_dir = install_chromium.install_dir(browsers_root, chromium)
    assert (product_dir / "chrome-linux64" / "chrome").read_bytes() \
        .startswith(b"#!/bin/sh")
    assert (product_dir / "INSTALLATION_COMPLETE").exists()
    record = json.loads(
        (product_dir / "DIGEST_VERIFIED").read_text(encoding="utf-8"))
    assert record["product"] == "chromium"
    assert record["revision"] == REVISION
    assert record["sha256"] == digests[("chromium", REVISION)]
    executable = product_dir / "chrome-linux64" / "chrome"
    # Mode semantics are POSIX-only and the browser consumers are
    # ubuntu-latest: Windows reports a fixed st_mode, so the assertion is
    # meaningless there — every non-mode assertion above ran on all OSes.
    if os.name != "nt":
        assert executable.stat().st_mode & 0o111
    assert stub_downloads == [[
        "https://cdn.playwright.dev/builds/cft/153.0.8010.12/linux64/"
        "chrome-linux64.zip"]]


