# --- helpers ------------------------------------------------------------

def registry():
    """The fixture browsers.json as build_products consumes it."""
    return {entry["name"]: entry for entry in BROWSERS_JSON["browsers"]}


def products(digests):
    return install_chromium.build_products(registry(), digests)


def write_zip(path: Path, entries) -> Path:
    """Build a real zip with unix modes, like playwright's archives."""
    with zipfile.ZipFile(path, "w") as archive:
        for name, data, mode in entries:
            info = zipfile.ZipInfo(name)
            is_dir = name.endswith("/")
            info.external_attr = (0o40755 << 16) | 0x10 if is_dir \
                else mode << 16
            archive.writestr(info, data)
    return path


def inodes_of(root: Path, seeded) -> dict:
    return {
        install_chromium.install_dir(root, product).name:
        install_chromium.install_dir(root, product).stat().st_ino
        for product in seeded
    }


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def patch_spec(monkeypatch, fake_spec):
    monkeypatch.setattr(install_chromium, "find_playwright_spec",
                        lambda: fake_spec)


